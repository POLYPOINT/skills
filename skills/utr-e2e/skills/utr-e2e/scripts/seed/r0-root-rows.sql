-- r0-root-rows.sql — Phase 1 step (j.1): root-node (KNOTEN_ID 1) DIENST_DETAIL rows for the seed Dienste 111/112/113/141,
-- copied from the team node, WITH their DIENST_BEZAHLTE_PAUSE rows, plus root DIENSTPALETTE rows for 111..141 and 145.
-- Run: scripts/sql.sh <tenant-id> -f scripts/seed/r0-root-rows.sql -D team_node=<Pflege palette node of E1–E4, audit A6>
-- Recovered from run a1801 (seed/j-r0.sql: details 1460–1463, pauses 1260–1263 created there); the "already there" guards
-- were added afterwards (re-running the file inserts nothing twice) and are unverified.
-- Sequences ECBERN.SEQID_DIENST_DETAIL / SEQID_DIENST_BEZAHLTE_PAUSE exist on the DeployMate master image; if not:
--   SELECT SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'ECBERN' AND SEQUENCE_NAME LIKE '%DIENST%';
-- Afterwards (seed README step j): restart PEP -> re-save each code in Definitionen › Dienst -> restart PEP -> G4b.
SET SERVEROUTPUT ON
DECLARE r ECBERN.DIENST_DETAIL%ROWTYPE; pos NUMBER; old_id NUMBER; v_pid NUMBER; n NUMBER;
BEGIN
  FOR c IN (SELECT COLUMN_VALUE AS PA FROM TABLE(SYS.ODCINUMBERLIST(111,112,113,141))) LOOP
    SELECT COUNT(*) INTO n FROM ECBERN.DIENST_DETAIL WHERE PA_CODE = c.PA AND KNOTEN_ID = 1;
    IF n = 0 THEN
      SELECT * INTO r FROM ECBERN.DIENST_DETAIL WHERE PA_CODE = c.PA AND KNOTEN_ID = &team_node AND ROWNUM = 1;
      old_id := r.DIENST_DETAIL_ID;
      r.DIENST_DETAIL_ID := ECBERN.SEQID_DIENST_DETAIL.NEXTVAL; r.KNOTEN_ID := 1;
      INSERT INTO ECBERN.DIENST_DETAIL VALUES r;
      FOR p IN (SELECT BLOCK_NR, BEGINN, ENDE FROM ECBERN.DIENST_BEZAHLTE_PAUSE WHERE DIENST_DETAIL_ID = old_id) LOOP
        v_pid := ECBERN.SEQID_DIENST_BEZAHLTE_PAUSE.NEXTVAL;
        INSERT INTO ECBERN.DIENST_BEZAHLTE_PAUSE (DIENST_BEZAHLTE_PAUSE_ID, DIENST_DETAIL_ID, BLOCK_NR, BEGINN, ENDE)
        VALUES (v_pid, r.DIENST_DETAIL_ID, p.BLOCK_NR, p.BEGINN, p.ENDE);
      END LOOP;
      DBMS_OUTPUT.PUT_LINE('detail '||c.PA||' root '||r.DIENST_DETAIL_ID||' from '||old_id);
    ELSE
      DBMS_OUTPUT.PUT_LINE('detail '||c.PA||' root row already there');
    END IF;
  END LOOP;
  FOR c IN (SELECT COLUMN_VALUE AS PA FROM TABLE(SYS.ODCINUMBERLIST(111,112,113,141,145))) LOOP
    SELECT COUNT(*) INTO n FROM ECBERN.DIENSTPALETTE WHERE KNOTEN_ID = 1 AND PA_CODE = c.PA;
    IF n = 0 THEN
      SELECT NVL(MAX(POSITION),0)+1 INTO pos FROM ECBERN.DIENSTPALETTE WHERE KNOTEN_ID = 1;
      INSERT INTO ECBERN.DIENSTPALETTE (KNOTEN_ID, PA_CODE, AUTO_PLANBAR, SHORTCUT, POSITION, NAME, PALETTE_GUELTIG_AB, PALETTE_GUELTIG_BIS)
      VALUES (1, c.PA, 'F', 0, pos, NULL, DATE '2000-01-01', DATE '2999-12-31');
    END IF;
  END LOOP;
  COMMIT;
END;
