SELECT 'ROOT|'||DIENST_DETAIL_ID||'|'||PA_CODE FROM ECBERN.DIENST_DETAIL WHERE KNOTEN_ID = 1 AND PA_CODE IN (111,112,113,141) ORDER BY PA_CODE;
SELECT 'PAUSE|'||p.DIENST_BEZAHLTE_PAUSE_ID||'|'||p.DIENST_DETAIL_ID||'|'||p.BEGINN||'-'||p.ENDE
  FROM ECBERN.DIENST_BEZAHLTE_PAUSE p JOIN ECBERN.DIENST_DETAIL d ON d.DIENST_DETAIL_ID = p.DIENST_DETAIL_ID
 WHERE d.KNOTEN_ID = 1 AND d.PA_CODE IN (111,112,113,141);
SELECT 'PAL1|'||PA_CODE||'|'||POSITION FROM ECBERN.DIENSTPALETTE WHERE KNOTEN_ID = 1 AND PA_CODE IN (111,112,113,141,145);
