-- verify-kits.sql — read-only check of the steward kits (definitions-kit.sql, role-kit.sql, kit-member.sql) on one env.
--   scripts/sql.sh <env> -f scripts/seed/common/verify-kits.sql -D env_role=X|Y
-- Prints CHECK|OK|… / CHECK|MISSING|… / CHECK|WARN|… lines (grep them; every MISSING blocks the groups that need it) and the
-- detail sections K1–K9. Log the CHECK lines in kits/<env> (coordination db). Run after S1 step 5 and in every daily pre-flight.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET FEEDBACK OFF
SET PAGESIZE 0
SET LINESIZE 400
DECLARE
  v_role VARCHAR2(10) := UPPER(TRIM('&env_role'));
  n NUMBER; has_ip NUMBER; v VARCHAR2(4000);
  PROCEDURE chk(p_ok BOOLEAN, p_what VARCHAR2, p_warn BOOLEAN DEFAULT FALSE) IS
  BEGIN DBMS_OUTPUT.PUT_LINE('CHECK|' || CASE WHEN p_ok THEN 'OK' WHEN p_warn THEN 'WARN' ELSE 'MISSING' END || '|' || p_what); END;
  FUNCTION cnt(p_sql VARCHAR2) RETURN NUMBER IS r NUMBER; BEGIN EXECUTE IMMEDIATE p_sql INTO r; RETURN r; END;
  PROCEDURE kitchk(p_name VARCHAR2, p_app NUMBER, p_rights VARCHAR2, p_maps VARCHAR2) IS g NUMBER; r NUMBER; tok VARCHAR2(60);
  BEGIN
    BEGIN SELECT POLYUSRGRPID, POLYUSRROLEID INTO g, r FROM ECBERN.POLYUSRGRP WHERE BEZEICHNUNG = p_name AND APP_ID = p_app;
    EXCEPTION WHEN NO_DATA_FOUND THEN chk(FALSE, 'kit group ' || p_name || ' (role-kit.sql)'); RETURN; END;
    chk(TRUE, 'kit group ' || p_name || ' id ' || g || ' role ' || r);
    FOR i IN 1 .. NVL(REGEXP_COUNT(p_rights, '[^,]+'), 0) LOOP
      tok := REGEXP_SUBSTR(p_rights, '[^,]+', 1, i);
      SELECT COUNT(*) INTO n FROM ECBERN.POLYUSRROLE_DETAIL WHERE POLYUSRROLEID = r AND APP_ID = p_app AND SUBID = -1 AND TRIM(WERT) = 'T'
         AND FUNKTIONSID = TO_NUMBER(REGEXP_SUBSTR(tok, '[^:]+', 1, 1)) AND OPERATION = TO_NUMBER(REGEXP_SUBSTR(tok, '[^:]+', 1, 2));
      chk(n > 0, p_name || ' right ' || tok);
    END LOOP;
    FOR i IN 1 .. NVL(REGEXP_COUNT(p_maps, '[^,]+'), 0) LOOP
      tok := REGEXP_SUBSTR(p_maps, '[^,]+', 1, i);
      SELECT COUNT(*) INTO n FROM ECBERN.POLYUSRROLE_KEYCLOAK_ROLE_MAPPING WHERE POLYUSRROLEID = r
         AND KEYCLOAK_ROLE = REGEXP_SUBSTR(tok, '[^/]+', 1, 1) AND (REGEXP_SUBSTR(tok, '[^/]+', 1, 2) IS NULL OR DOMAIN = REGEXP_SUBSTR(tok, '[^/]+', 1, 2));
      chk(n > 0, p_name || ' mapping ' || tok);
    END LOOP;
    SELECT COUNT(*) INTO n FROM ECBERN.POLYUSER_POLYUSRGRP WHERE POLYUSRGRPID = g;
    DBMS_OUTPUT.PUT_LINE('INFO|' || p_name || '|members ' || n);
  END;
BEGIN
  IF v_role NOT IN ('X', 'Y') THEN RAISE_APPLICATION_ERROR(-20002, 'env_role must be X or Y'); END IF;
  -- definitions
  FOR c IN (SELECT 111 AS PA, 1 AS T FROM dual UNION ALL SELECT 113, 2 FROM dual UNION ALL SELECT 112, 3 FROM dual UNION ALL SELECT 141, 4 FROM dual) LOOP
    SELECT COUNT(*) INTO n FROM ECBERN.DIENST WHERE PA_CODE = c.PA AND POMASCHICHTTYP = c.T;
    chk(n = 1, 'POMA shift type ' || c.PA || ' = ' || c.T);
  END LOOP;
  SELECT COUNT(*) INTO n FROM ECBERN.DIENST_DETAIL WHERE PA_CODE IN (111, 112, 113, 141) AND KNOTEN_ID = 1;
  chk(n >= 4, 'R0 root details for 111/112/113/141 (r0-root-rows.sql): ' || n);
  SELECT COUNT(*) INTO n FROM ECBERN.HIERARCHIE WHERE STAMM IS NULL;
  chk(n = 0, 'HIERARCHIE.STAMM filled (stamm-fix.sql): ' || n || ' NULL', TRUE);
  IF v_role = 'X' THEN
    SELECT COUNT(*) INTO n FROM ECBERN.DIENST WHERE PA_CODE IN (111, 112, 113) AND TRIM(DIENSTTAUSCH) = 'T';
    chk(n = 3, 'DIENSTTAUSCH T on 111/112/113: ' || n);
    SELECT COUNT(*) INTO n FROM ECBERN.DIENST WHERE PA_CODE = 141 AND NVL(TRIM(DIENSTTAUSCH), 'F') = 'F';
    chk(n = 1, '141 stays non-swappable');
    SELECT COUNT(*) INTO n FROM ECBERN.DIENST d WHERE TRIM(d.TYP) = 'A' AND TRIM(d.DIENSTTAUSCH) = 'T';
    chk(n >= 1, 'a swappable absence exists: ' || n);
    SELECT COUNT(*) INTO n FROM ECBERN.DIENST_DETAIL WHERE PA_CODE IN (111, 112, 113) AND NVL(TRIM(DIENST_TEILEN), 'F') <> 'T';
    chk(n = 0, 'DIENST_TEILEN T on every detail of 111/112/113: ' || n || ' rows not T');
    SELECT COUNT(*) INTO has_ip FROM ALL_TAB_COLUMNS WHERE OWNER = 'ECBERN' AND TABLE_NAME = 'DIENST' AND COLUMN_NAME = 'INTERNER_POOL';
    IF has_ip = 1 THEN
      n := cnt(q'[SELECT COUNT(*) FROM ECBERN.DIENST WHERE PA_CODE IN (111, 112, 113) AND TRIM(INTERNER_POOL) = 'T']');
      chk(n = 3, 'INTERNER_POOL T on 111/112/113: ' || n);
    ELSE chk(FALSE, 'INTERNER_POOL column absent (bundle older than feature-26-3)', TRUE); END IF;
    kitchk('E2E:SP-ALL', 2471, '1050:6,1061:6,1070:6', 'ROLE_SHIFT_PLANNER/RESOURCE_REPLACEMENT,ROLE_SHIFT_PLANNER/INTERNAL_POOL');
    kitchk('E2E:PM-ALL', 2471, '1060:6', 'ROLE_POOL_MANAGER/INTERNAL_POOL');
    kitchk('E2E:EXTPOOL', 2471, '1065:6,1062:6', NULL);
    kitchk('E2E:HP-NOSWAP', 2610, '', NULL);
    SELECT COUNT(*) INTO n FROM ECBERN.POLYUSRROLE_DETAIL d JOIN ECBERN.POLYUSRGRP g ON g.POLYUSRROLEID = d.POLYUSRROLEID
     WHERE g.BEZEICHNUNG = 'E2E:HP-NOSWAP' AND d.FUNKTIONSID IN (200005, 200015) AND TRIM(d.WERT) = 'T';
    chk(n = 0, 'E2E:HP-NOSWAP grants neither 200005 nor 200015');
  ELSE
    kitchk('E2E:PLANALL', 2471, '1050:6,1060:6,1061:6,1070:6', 'ROLE_SHIFT_PLANNER/RESOURCE_REPLACEMENT,ROLE_POOL_MANAGER/INTERNAL_POOL,ROLE_SHIFT_PLANNER/INTERNAL_POOL');
    kitchk('E2E:SP-GA', 2471, '1050:6,1061:6,1070:6', 'ROLE_SHIFT_PLANNER/RESOURCE_REPLACEMENT');
    kitchk('E2E:PM-GA', 2471, '1060:6', 'ROLE_POOL_MANAGER/INTERNAL_POOL');
    kitchk('E2E:TA', 2610, '200015:6,200010:6', 'ROLE_TENANT_ADMIN');
    kitchk('E2E:HP-PLAIN', 2471, '1030:6,306:6,307:2,307:3,307:4,1033:2,1033:3,1033:4,1032:3,1032:4,1031:3,1031:4,1040:1', NULL);
    SELECT COUNT(*) INTO n FROM ECBERN.POLYUSER_POLYUSRGRP ug JOIN ECBERN.POLYUSRGRP g ON g.POLYUSRGRPID = ug.POLYUSRGRPID WHERE g.BEZEICHNUNG = 'E2E:TA';
    chk(n >= 1, 'TA is a member of E2E:TA (steward: kit-member.sql)');
    SELECT COUNT(*) INTO n FROM ECBERN.POLYKNOTENAUSWAHL k JOIN ECBERN.POLYKNOTENAUSWAHL_DETAIL d ON d.POLYKNOTENAUSWAHLID = k.POLYKNOTENAUSWAHLID WHERE k.TITEL = 'E2E:G-A';
    chk(n = 1, 'node selection E2E:G-A has exactly one node: ' || n);
  END IF;
  -- kit members who still hold the rights they should lack
  FOR m IN (SELECT DISTINCT k.BEZEICHNUNG AS KIT, u.KUERZEL, o.BEZEICHNUNG AS OTHER, NVL(TRIM(r.LEITBEDIENER), 'F') AS LB
              FROM ECBERN.POLYUSRGRP k JOIN ECBERN.POLYUSER_POLYUSRGRP km ON km.POLYUSRGRPID = k.POLYUSRGRPID
              JOIN ECBERN.POLYUSER u ON u.USER_ID = km.USER_ID
              JOIN ECBERN.POLYUSER_POLYUSRGRP om ON om.USER_ID = km.USER_ID
              JOIN ECBERN.POLYUSRGRP o ON o.POLYUSRGRPID = om.POLYUSRGRPID
              LEFT JOIN ECBERN.POLYUSRROLE r ON r.POLYUSRROLEID = o.POLYUSRROLEID
             WHERE k.BEZEICHNUNG IN ('E2E:HP-NOSWAP', 'E2E:SP-GA', 'E2E:PM-GA', 'E2E:TA', 'E2E:HP-PLAIN')
               AND (o.BEZEICHNUNG = 'DMSEED:Planner' OR NVL(TRIM(r.LEITBEDIENER), 'F') = 'T'
                    OR (k.BEZEICHNUNG = 'E2E:HP-NOSWAP' AND EXISTS (SELECT 1 FROM ECBERN.POLYUSRROLE_DETAIL x WHERE x.POLYUSRROLEID = o.POLYUSRROLEID AND x.FUNKTIONSID = 200005 AND TRIM(x.WERT) = 'T')))) LOOP
    chk(FALSE, m.KIT || ' member ' || LOWER(m.KUERZEL) || ' is still in "' || m.OTHER || '"' || CASE WHEN m.LB = 'T' THEN ' (LEITBEDIENER)' END || ': leave it if the group gate shows the unwanted right (kit-member.sql)', TRUE);
  END LOOP;
END;
/
PROMPT == K1 definitions (TAUSCH = DIENSTTAUSCH, TYP0 = POMASCHICHTTYP, ERSATZ = RESSOURCENERSATZ)
SELECT 'K1|' || d.PA_CODE || '|' || TRIM(d.TYP) || '|TAUSCH=' || TRIM(d.DIENSTTAUSCH) || '|TYP0=' || d.POMASCHICHTTYP || '|ERSATZ=' || TRIM(d.RESSOURCENERSATZ)
       || '|WUNSCH=' || TRIM(d.PLANUNGSWUNSCH) || '|IMMER=' || TRIM(d.ALWAYS_VISIBLE) || '|' || SUBSTR(d.TITEL, 1, 30)
  FROM ECBERN.DIENST d WHERE d.PA_CODE IN (111, 112, 113, 141, 145) OR TRIM(d.DIENSTTAUSCH) = 'T' ORDER BY d.PA_CODE;
PROMPT == K2 detail rows of 111/112/113/141 (node, DIENST_TEILEN)
SELECT 'K2|' || PA_CODE || '|node ' || KNOTEN_ID || '|TEILEN=' || TRIM(DIENST_TEILEN) FROM ECBERN.DIENST_DETAIL WHERE PA_CODE IN (111, 112, 113, 141) ORDER BY PA_CODE, KNOTEN_ID;
PROMPT == K3 palettes with absences (node: PA/TYP)
SELECT 'K3|node ' || p.KNOTEN_ID || '|' || SUBSTR(k.NAME, 1, 30) || '|' || LISTAGG(p.PA_CODE || '/' || TRIM(d.TYP), ' ') WITHIN GROUP (ORDER BY p.PA_CODE)
  FROM ECBERN.DIENSTPALETTE p JOIN ECBERN.DIENST d ON d.PA_CODE = p.PA_CODE LEFT JOIN ECBERN.KNOTEN k ON k.ID = p.KNOTEN_ID
 WHERE p.PALETTE_GUELTIG_BIS IS NULL OR p.PALETTE_GUELTIG_BIS >= TRUNC(SYSDATE)
 GROUP BY p.KNOTEN_ID, k.NAME HAVING SUM(CASE WHEN TRIM(d.TYP) = 'A' THEN 1 ELSE 0 END) > 0 ORDER BY 1;
PROMPT == K4 kit roles: rights (f:op) and Keycloak mappings
SELECT 'K4|' || g.BEZEICHNUNG || '|grp ' || g.POLYUSRGRPID || '|app ' || g.APP_ID || '|role ' || g.POLYUSRROLEID || '|sel ' || g.POLYKNOTENAUSWAHLID_MODIFIBAR || '|'
       || (SELECT LISTAGG(d.FUNKTIONSID || ':' || d.OPERATION, ',') WITHIN GROUP (ORDER BY d.FUNKTIONSID, d.OPERATION) FROM ECBERN.POLYUSRROLE_DETAIL d WHERE d.POLYUSRROLEID = g.POLYUSRROLEID AND TRIM(d.WERT) = 'T') || '|'
       || (SELECT LISTAGG(m.KEYCLOAK_ROLE || '/' || m.DOMAIN, ',') WITHIN GROUP (ORDER BY m.KEYCLOAK_ROLE) FROM ECBERN.POLYUSRROLE_KEYCLOAK_ROLE_MAPPING m WHERE m.POLYUSRROLEID = g.POLYUSRROLEID)
  FROM ECBERN.POLYUSRGRP g WHERE g.BEZEICHNUNG LIKE 'E2E:%' ORDER BY g.BEZEICHNUNG;
PROMPT == K5 node selections of the kit (selection: nodes)
SELECT 'K5|' || k.TITEL || '|' || k.POLYKNOTENAUSWAHLID || '|' || LISTAGG(d.KNOTEN_ID, ',') WITHIN GROUP (ORDER BY d.KNOTEN_ID)
  FROM ECBERN.POLYKNOTENAUSWAHL k JOIN ECBERN.POLYKNOTENAUSWAHL_DETAIL d ON d.POLYKNOTENAUSWAHLID = k.POLYKNOTENAUSWAHLID
 WHERE k.TITEL LIKE 'E2E:%' GROUP BY k.TITEL, k.POLYKNOTENAUSWAHLID ORDER BY 1;
PROMPT == K6 kit members (kit: login MA_ID default) and all their groups
SELECT 'K6|' || g.BEZEICHNUNG || '|' || LOWER(u.KUERZEL) || '|MA ' || mp.ID || '|default ' || NVL(TRIM(ug.DEFAULTGRP), '-') || '|all: '
       || (SELECT LISTAGG(o.BEZEICHNUNG || CASE WHEN TRIM(om.DEFAULTGRP) = 'T' THEN '*' END, '; ') WITHIN GROUP (ORDER BY o.APP_ID, o.BEZEICHNUNG)
             FROM ECBERN.POLYUSER_POLYUSRGRP om JOIN ECBERN.POLYUSRGRP o ON o.POLYUSRGRPID = om.POLYUSRGRPID WHERE om.USER_ID = u.USER_ID)
  FROM ECBERN.POLYUSRGRP g JOIN ECBERN.POLYUSER_POLYUSRGRP ug ON ug.POLYUSRGRPID = g.POLYUSRGRPID
  JOIN ECBERN.POLYUSER u ON u.USER_ID = ug.USER_ID LEFT JOIN ECBERN.MITARBEITER_POLYUSER mp ON mp.USER_ID = u.USER_ID
 WHERE g.BEZEICHNUNG LIKE 'E2E:%' ORDER BY g.BEZEICHNUNG, u.KUERZEL;
PROMPT == K7 seed groups (group: members, LEITBEDIENER role) — what every seed login holds before any move
SELECT 'K7|' || g.BEZEICHNUNG || '|grp ' || g.POLYUSRGRPID || '|app ' || g.APP_ID || '|role ' || g.POLYUSRROLEID || CASE WHEN TRIM(r.LEITBEDIENER) = 'T' THEN '|LEITBEDIENER' END
       || '|members ' || COUNT(*) || '|default ' || SUM(CASE WHEN TRIM(ug.DEFAULTGRP) = 'T' THEN 1 ELSE 0 END)
  FROM ECBERN.POLYUSER_POLYUSRGRP ug JOIN ECBERN.POLYUSRGRP g ON g.POLYUSRGRPID = ug.POLYUSRGRPID JOIN ECBERN.POLYUSER u ON u.USER_ID = ug.USER_ID
  LEFT JOIN ECBERN.POLYUSRROLE r ON r.POLYUSRROLEID = g.POLYUSRROLEID
 WHERE u.KUERZEL LIKE 'DMSEED-%' AND g.BEZEICHNUNG NOT LIKE 'E2E:%'
 GROUP BY g.BEZEICHNUNG, g.POLYUSRGRPID, g.APP_ID, g.POLYUSRROLEID, r.LEITBEDIENER ORDER BY g.APP_ID, g.BEZEICHNUNG;
PROMPT == K8 Keycloak role mappings of the seed groups' roles (where the seed logins' cloud roles come from)
SELECT 'K8|' || g.BEZEICHNUNG || '|role ' || g.POLYUSRROLEID || '|' || LISTAGG(m.KEYCLOAK_ROLE || '/' || m.DOMAIN, ',') WITHIN GROUP (ORDER BY m.KEYCLOAK_ROLE)
  FROM ECBERN.POLYUSRGRP g JOIN ECBERN.POLYUSRROLE_KEYCLOAK_ROLE_MAPPING m ON m.POLYUSRROLEID = g.POLYUSRROLEID
 WHERE g.POLYUSRGRPID IN (SELECT ug.POLYUSRGRPID FROM ECBERN.POLYUSER_POLYUSRGRP ug JOIN ECBERN.POLYUSER u ON u.USER_ID = ug.USER_ID WHERE u.KUERZEL LIKE 'DMSEED-%')
 GROUP BY g.BEZEICHNUNG, g.POLYUSRROLEID ORDER BY 1;
PROMPT == K9 roles of seed logins that grant 200005 Diensttausch einreichen (swap HPX must leave these groups)
SELECT 'K9|' || g.BEZEICHNUNG || '|grp ' || g.POLYUSRGRPID || '|app ' || g.APP_ID || '|role ' || g.POLYUSRROLEID
  FROM ECBERN.POLYUSRGRP g
 WHERE EXISTS (SELECT 1 FROM ECBERN.POLYUSRROLE_DETAIL d WHERE d.POLYUSRROLEID = g.POLYUSRROLEID AND d.FUNKTIONSID = 200005 AND TRIM(d.WERT) = 'T')
   AND g.POLYUSRGRPID IN (SELECT ug.POLYUSRGRPID FROM ECBERN.POLYUSER_POLYUSRGRP ug JOIN ECBERN.POLYUSER u ON u.USER_ID = ug.USER_ID WHERE u.KUERZEL LIKE 'DMSEED-%')
 ORDER BY 1;
